#pragma once
// rng.h — portable random-number helpers.
//
// The C++ standard fully specifies the output sequence of std::mt19937, but NOT
// the algorithms behind std::uniform_int_distribution, std::uniform_real_distribution
// or std::discrete_distribution: libc++ (Apple Clang), libstdc++ (GCC) and MSVC
// all implement them differently. A program that uses them therefore produces
// different runs on different platforms even with the same seed.
//
// The functions below re-implement the three distributions with the exact
// arithmetic used by libc++ (LLVM), so that
//   * every platform/compiler produces bit-identical random streams, and
//   * the streams are identical to those of the original macOS/Apple Clang build
//     (which used the libc++ distributions), so the input instances in data/
//     are regenerated byte-for-byte.
#include <cstdint>
#include <random>
#include <vector>
#include <algorithm>
#include <numeric>

using Rng = std::mt19937;

// libc++ std::generate_canonical<double, 53>(mt19937): two 32-bit draws.
inline double rand_real(Rng& g) {
    double s = static_cast<double>(static_cast<uint32_t>(g()));
    s += static_cast<double>(static_cast<uint32_t>(g())) * 4294967296.0;   // 2^32
    return s / 18446744073709551616.0;                                     // 2^64
}

// libc++ std::uniform_int_distribution<int>(a, b)(mt19937):
// draw w low bits and reject values >= range.
inline int rand_int(Rng& g, int a, int b) {
    const uint32_t rp = static_cast<uint32_t>(b) - static_cast<uint32_t>(a) + 1u;
    if (rp == 1u) return a;
    if (rp == 0u) return static_cast<int>(static_cast<uint32_t>(g()));
    int w = 32 - __builtin_clz(rp) - 1;
    if ((rp & (0xFFFFFFFFu >> (32 - w))) != 0u) ++w;
    const uint32_t mask = (w >= 32) ? 0xFFFFFFFFu : ((1u << w) - 1u);
    uint32_t u;
    do { u = static_cast<uint32_t>(g()) & mask; } while (u >= rp);
    return static_cast<int>(u + static_cast<uint32_t>(a));
}

// libc++ std::discrete_distribution<int>(weights)(mt19937).
class DiscreteDist {
    std::vector<double> cum_;   // partial sums of the first n-1 normalised weights
public:
    explicit DiscreteDist(std::vector<double> w) {
        if (w.size() > 1) {
            const double s = std::accumulate(w.begin(), w.end(), 0.0);
            for (double& x : w) x /= s;
            cum_.resize(w.size() - 1);
            std::partial_sum(w.begin(), w.end() - 1, cum_.begin());
        }
    }
    int operator()(Rng& g) const {
        const double u = rand_real(g);
        return static_cast<int>(std::upper_bound(cum_.begin(), cum_.end(), u) - cum_.begin());
    }
};
